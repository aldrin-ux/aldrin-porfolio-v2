import sharp from "sharp";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";

// Regenerate from the original screenshots, never from the tiny legacy WebPs.
// Filenames contain a byte-content hash so only these variants can be cached immutably.
const directory = "public/assets/optimized";
await mkdir(directory, { recursive: true });
const assets = {};
const records = [];
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex").slice(0, 12);

async function variants(name, input, widths, crop) {
  const metadata = await sharp(input).metadata();
  const originalHeight = crop ? Math.round(metadata.width * 10 / 16) : metadata.height;
  const images = [];
  for (const width of widths) {
    let pipeline = sharp(input);
    if (crop) pipeline = pipeline.extract({ left: 0, top: 0, width: metadata.width, height: originalHeight });
    const bytes = await pipeline.resize({ width, withoutEnlargement: true }).webp({ quality: 90, effort: 6 }).toBuffer();
    const actual = await sharp(bytes).metadata();
    const filename = `${name}-${actual.width}.${digest(bytes)}.webp`;
    await writeFile(`${directory}/${filename}`, bytes);
    images.push({ src: `/assets/optimized/${filename}`, width: actual.width, height: actual.height, bytes: bytes.length });
  }
  const fallback = images[images.length - 1];
  records.push({ name, original: metadata.size, variants: images });
  return { src: fallback.src, width: fallback.width, height: fallback.height, srcset: images.map((image) => `${image.src} ${image.width}w`).join(", ") };
}

for (const name of ["dazlab", "mortar", "handl", "tangilla"]) {
  const input = await readFile(`public/assets/${name}.png`);
  assets[`/assets/${name}.png`] = {
    card: await variants(`${name}-card`, input, [480, 800, 1200], true),
    study: await variants(`${name}-study`, input, [480, 960, 1440, 1920], false),
  };
}
// Both Dazlab originals are identical; reuse the same generated variants.
assets["/assets/dazlab-case.png"] = assets["/assets/dazlab.png"];
const heroImage = await variants("aldrin-hero", await readFile("public/assets/aldrin-hero.webp"), [320, 512], false);
await writeFile("src/content/imageAssets.ts", `// Generated by scripts/generate-image-variants.mjs.\ninterface Variant { src: string; width: number; height: number; srcset: string; }\nexport const imageAssets: Record<string, { card: Variant; study: Variant }> = ${JSON.stringify(assets, null, 2)};\nexport const heroImage = ${JSON.stringify(heroImage, null, 2)};\n`);
await mkdir("audit/ald-109", { recursive: true });
await writeFile("audit/ald-109/image-variants.json", JSON.stringify(records, null, 2) + "\n");
console.log(`Generated ${records.reduce((sum, record) => sum + record.variants.length, 0)} content-hashed WebP variants.`);
